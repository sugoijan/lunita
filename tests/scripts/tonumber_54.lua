-- Number parsing follows Lua 5.4 (also passes under PUC-Rio Lua 5.4.9).

assert(tonumber('0xffffffffffffffff') == -1)
assert(tonumber('0x' .. ('f'):rep(100)) == -1)
assert(tonumber('0x10') == 16 and math.type(tonumber('0x10')) == 'integer')
assert(tonumber('inf') == nil and tonumber('nan') == nil and tonumber('infinity') == nil)
assert(tonumber('1e99999') == math.huge)
assert(tonumber('  10  ') == 10 and tonumber('10 x') == nil)
assert(tonumber('1\0') == nil)
assert(tonumber('', 10) == nil and tonumber('-', 10) == nil and tonumber(' ', 16) == nil)
assert(tonumber('ff', 16) == 255 and tonumber('-ff', 16) == -255 and tonumber('zz', 36) == 1295)
assert(tonumber('  11  ', 2) == 3)
assert(not pcall(tonumber, 10, 16))
assert(not pcall(tonumber))
assert(tonumber(nil) == nil)
assert(0xffffffffffffffff == -1)
assert('10' + 1 == 11 and math.type('10' + 1) == 'integer')
assert('0x10' + 0 == 16)
assert(not pcall(function() return 'inf' + 0 end))
